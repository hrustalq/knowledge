// Response schemas for the OpenAPI document, generated from the
// @knowledge/contracts types the routes return (#472).
//
// Every `@Returns('Name')` in a controller names a contracts type. This script
// collects those names, turns each type into a JSON schema, and writes two
// files that are committed beside the code that reads them:
//   src/config/contract-schemas.json      — merged into components.schemas by config/swagger.ts
//   src/common/contract-responses.generated.ts — name → type, so @Returns can check the handler
// Run by `make api-schema` before the build. A name that is not a contracts
// type fails here, not in the browser.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { createGenerator } from 'ts-json-schema-generator'

const root = join(import.meta.dirname, '..')
const src = join(root, 'src')

function controllers(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? controllers(join(dir, e.name)) : e.name.endsWith('.controller.ts') ? [join(dir, e.name)] : [],
  )
}

const names = new Set()
for (const file of controllers(src)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/@Returns\(\s*'([A-Za-z0-9_]+)'/g)) names.add(m[1])
}
const sorted = [...names].sort()

const generator = createGenerator({
  path: join(root, '../../packages/contracts/src/index.ts'),
  tsconfig: join(root, 'tsconfig.json'),
  skipTypeCheck: true,
  expose: 'export',
  topRef: false,
  jsDoc: 'none',
  additionalProperties: true,
})

const definitions = {}
for (const name of sorted) {
  const schema = generator.createSchema(name)
  Object.assign(definitions, schema.definitions, { [name]: schema.definitions?.[name] ?? stripMeta(schema) })
}

function stripMeta(schema) {
  const { $schema: _s, definitions: _d, ...rest } = schema
  return rest
}

/**
 * The generator writes JSON Schema (draft 7); the document is OpenAPI 3.0,
 * which spells three things differently: a nullable value is `nullable: true`,
 * not a `null` member of `type` or of an `anyOf`, and a literal is a one-value
 * `enum`, not `const`.
 */
function toOpenApi30(node) {
  if (Array.isArray(node)) return node.map(toOpenApi30)
  if (!node || typeof node !== 'object') return node
  const out = Object.fromEntries(Object.entries(node).map(([k, v]) => [k, toOpenApi30(v)]))
  if ('const' in out) {
    out.enum = [out.const]
    delete out.const
  }
  if (Array.isArray(out.type)) {
    const types = out.type.filter((t) => t !== 'null')
    if (types.length < out.type.length) out.nullable = true
    if (types.length === 1) out.type = types[0]
    else {
      delete out.type
      out.anyOf = types.map((type) => ({ type }))
    }
  }
  if (Array.isArray(out.anyOf) && out.anyOf.some((m) => m.type === 'null' && Object.keys(m).length === 1)) {
    out.anyOf = out.anyOf.filter((m) => !(m.type === 'null' && Object.keys(m).length === 1))
    out.nullable = true
  }
  return out
}

const json = JSON.stringify(
  Object.fromEntries(Object.keys(definitions).sort().map((k) => [k, toOpenApi30(definitions[k])])),
  null,
  2,
).replaceAll('#/definitions/', '#/components/schemas/')
writeFileSync(join(src, 'config/contract-schemas.json'), json + '\n')

writeFileSync(
  join(src, 'common/contract-responses.generated.ts'),
  `// Generated by scripts/generate-contract-schemas.mjs — do not edit (make api-schema).
${sorted.length ? `import type {\n${sorted.map((n) => `  ${n},`).join('\n')}\n} from '@knowledge/contracts';\n` : ''}
/** Every contracts type a route declares with \`@Returns\`, by name. */
export interface ContractResponses {
${sorted.map((n) => `  ${n}: ${n};`).join('\n')}
}
`,
)

console.log(`contract schemas: ${sorted.length} route types, ${Object.keys(definitions).length} definitions → ${relative(root, join(src, 'config/contract-schemas.json'))}`)
