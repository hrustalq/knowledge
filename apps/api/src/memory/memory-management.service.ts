/**
 * A parsed file's markdown as retain items' text, each at most `maxChars`:
 * paragraphs packed together, a paragraph longer than that cut into slices.
 */
export function splitText(text: string, maxChars: number): string[] {
  const parts: string[] = [];
  let current = '';
  for (const paragraph of text.split(/\n{2,}/)) {
    if (!paragraph.trim()) continue;
    for (let i = 0; i < paragraph.length; i += maxChars) {
      const piece = paragraph.slice(i, i + maxChars);
      if (current && current.length + 2 + piece.length <= maxChars) current += `\n\n${piece}`;
      else {
        if (current) parts.push(current);
        current = piece;
      }
    }
  }
  if (current) parts.push(current);
  return parts;
}

/** `rows` in runs of at most `size`. */
const batchesOf = <T>(rows: T[], size: number): T[][] => Array.from({ length: Math.ceil(rows.length / size) }, (_, i) => rows.slice(i * size, (i + 1) * size));

